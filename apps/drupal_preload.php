<?php

/**
 * Writes an OPcache preload file for an installed Drupal site.
 *
 * Drupal core ships no preload support, and nothing else in the toolchain does
 * either, so this is the only place a Drupal preload file is generated. It reads
 * the Composer classmap (the site must already have been dump-autoload'ed with
 * --optimize, or the map is nearly empty and the file is useless) and writes:
 *
 *   <site>/preload.php   the file opcache.preload points at
 *   <site>/preload.ini   an ini fragment that sets opcache.preload
 *
 * The cell helper mounts preload.ini into the runtime container only when it
 * exists, so a site without one behaves exactly as before.
 *
 * Why a prefix list and not the whole classmap: preloading every class in a
 * Drupal vendor directory is tens of thousands of classes and the win does not
 * grow with count -- what matters is the classes every request loads. The
 * defaults cover Drupal core and the Symfony components on the request path.
 *
 *   php drupal_preload.php <site-dir> [prefix ...]
 *
 * See docs/drupal-perf-opportunities.md for the measurement plan.
 */

declare(strict_types=1);

$site = rtrim($argv[1] ?? '', '/');
if ($site === '' || !is_dir($site)) {
    fwrite(STDERR, "usage: drupal_preload.php <site-dir> [prefix ...]\n");
    exit(2);
}

$prefixes = array_slice($argv, 2);
if ($prefixes === []) {
    $prefixes = [
        'Drupal\\Core\\',
        'Drupal\\Component\\',
        'Symfony\\Component\\HttpKernel\\',
        'Symfony\\Component\\HttpFoundation\\',
        'Symfony\\Component\\Routing\\',
        'Symfony\\Component\\DependencyInjection\\',
        'Symfony\\Component\\Runtime\\',
    ];
}

$classmapFile = "$site/vendor/composer/autoload_classmap.php";
if (!is_file($classmapFile)) {
    fwrite(STDERR, "drupal_preload: no $classmapFile (run composer dump-autoload first)\n");
    exit(1);
}

/** @var array<string, string> $classmap */
$classmap = require $classmapFile;

$classes = [];
foreach (array_keys($classmap) as $class) {
    foreach ($prefixes as $prefix) {
        if (str_starts_with($class, $prefix)) {
            $classes[] = $class;
            break;
        }
    }
}

if ($classes === []) {
    fwrite(STDERR, "drupal_preload: the classmap has no classes for the requested prefixes; "
        . "was the autoloader optimized?\n");
    exit(1);
}

// Deterministic output: a preload file that changes order between builds makes
// two apparently identical images differ.
sort($classes);

$export = var_export($classes, true);
$php = <<<PHP
<?php

/**
 * Generated by apps/drupal_preload.php. Do not edit.
 *
 * Loaded once per PHP process before the first request; the classes below stay
 * in the opcode cache for the process's lifetime.
 */

declare(strict_types=1);

require __DIR__ . '/vendor/autoload.php';

foreach ($export as \$class) {
    if (class_exists(\$class, false) || interface_exists(\$class, false) || trait_exists(\$class, false)) {
        continue;
    }
    // Autoload, so the class definition reaches the opcode cache now.
    class_exists(\$class) || interface_exists(\$class) || trait_exists(\$class);
}

PHP;

file_put_contents("$site/preload.php", $php);

$ini = <<<INI
; Generated by apps/drupal_preload.php. Mounted into the runtime container by
; bench/cells.sh when it exists.
opcache.preload=/app/preload.php
INI;
file_put_contents("$site/preload.ini", $ini . "\n");

printf("drupal_preload: %d classes -> %s/preload.php (+ preload.ini)\n", count($classes), $site);
